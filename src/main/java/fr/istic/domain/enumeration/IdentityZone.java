package fr.istic.domain.enumeration;

/** Zones of the exam template where the student writes who they are. */
public enum IdentityZone {
    /** Last name: {@code Exam.namezone}. */
    NAME,
    /** First name: {@code Exam.firstnamezone}. */
    FIRSTNAME,
    /** Student number: {@code Exam.idzone}. */
    INE,
}
